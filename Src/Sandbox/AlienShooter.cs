	protected override void Initialize()
	{
		Console.WriteLine("Ready to kill some alien scum?");
		Console.ReadLine();

		Player player = new(5, 5, '@', ConsoleColor.Green)
		{
			Layer = 1
		};
		Entity.Instantiate(player);

		Ball ball = new(5, 5, 'O', ConsoleColor.Blue)
		{
			Layer = 1
		};
		Entity.Instantiate(ball);
	}

	protected override void Update()
	{
		if (Input.GetKeyDown(ConsoleKey.Spacebar))
		{
			Console.ForegroundColor = (ConsoleColor)Random.Shared.Next(9, 16);
			Console.WriteLine("SPACE");
		}
	}

	protected override void Draw(IRenderer renderer)
	{
		DrawMap(renderer);
		DrawEntities(1);
	}

	void DrawMap(IRenderer renderer)
	{
		for (int y = 0; y < _layerZeroMap.Length; y++)
		{
			for (int x = 0; x < _layerZeroMap[y].Length; x++)
			{
				char tile = _layerZeroMap[y][x];

				if (tile == ' ')
					continue;

				// Default
				ConsoleColor fgColor = ConsoleColor.White;
				ConsoleColor bgColor = ConsoleColor.Black;

				switch (tile)
				{
					case '#': fgColor = ConsoleColor.Gray; break;       // Wall
					case '.': fgColor = ConsoleColor.DarkGray; break;   // Floor
					case '^':                                           // Door
						fgColor = ConsoleColor.Yellow;
						bgColor = ConsoleColor.DarkYellow;
						break;
					case 'O': fgColor = ConsoleColor.DarkGray; break;      // Statue
					case ':': fgColor = ConsoleColor.DarkRed; break;    // Rubble
					case ',': fgColor = ConsoleColor.DarkGreen; break;  // Moss
					case '\'': fgColor = ConsoleColor.Green; break;     // Vine
					case '%': fgColor = ConsoleColor.Magenta; break;    // Spore
					case '~':                                           // Water
						fgColor = ConsoleColor.Cyan;
						bgColor = ConsoleColor.DarkBlue;
						break;
					case '=':                                           // Water ripple
						fgColor = ConsoleColor.White;
						bgColor = ConsoleColor.DarkCyan;
						break;
				}

				// Safely pass both foreground and background to your renderer
				renderer.SetCell(x, y, tile, fgColor, bgColor);
			}
		}
	}
}